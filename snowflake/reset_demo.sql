-- FOI Sentinel v2 — demo state reset (run before any re-record or live showing)
-- Connection: PG-SNOWFLAKE   Schema: FOI.FOI_SENTINEL_V2
-- Undoes Act 1 Beat 2 (board drag) and Beat 3 (quick-wins batch send).
-- Safe to run repeatedly. Verified 2026-07-11.

-- 1. Re-open the six quick-wins, restore baseline outcomes, clear close fields.
UPDATE FOI.FOI_SENTINEL_V2.FOI_CASE
SET STATUS='OPEN',
    CLOSED_DATE=NULL,
    ANSWERED_IN_TIME=NULL,
    CLOCK_STATE='RUNNING',
    CLOCK_STOPPED_AT=NULL,
    OUTCOME = CASE WHEN REFERENCE IN ('FOI-2026-0108','FOI-2026-0109') THEN 'S21_REUSE' ELSE NULL END,
    UPDATED_AT=CURRENT_TIMESTAMP()
WHERE REFERENCE IN ('FOI-2026-0108','FOI-2026-0109','FOI-2026-0126','FOI-2026-0128','FOI-2026-0114','FOI-2026-0102');

-- 2. Move FOI-2026-0119 back to COST (undo the Beat 2 board drag to EXEMPTIONS).
UPDATE FOI.FOI_SENTINEL_V2.FOI_CASE
SET CURRENT_STAGE='COST', UPDATED_AT=CURRENT_TIMESTAMP()
WHERE REFERENCE='FOI-2026-0119';

-- 3. Un-dispatch the six quick-win drafts (keep DRAFT_TEXT so cards stay ready-to-send).
UPDATE FOI.FOI_SENTINEL_V2.FOI_RESPONSE
SET DISPATCHED_AT=NULL, FINAL_TEXT=NULL, SIGNED_OFF_BY=NULL
WHERE CASE_ID IN (
  SELECT CASE_ID FROM FOI.FOI_SENTINEL_V2.FOI_CASE
  WHERE REFERENCE IN ('FOI-2026-0108','FOI-2026-0109','FOI-2026-0126','FOI-2026-0128','FOI-2026-0114','FOI-2026-0102')
);

-- 4. Remove the demo-generated stage-advance events (keeps the activity log pristine).
DELETE FROM FOI.FOI_SENTINEL_V2.FOI_CASE_EVENT
WHERE EVENT_TYPE='STAGE_ADVANCE'
  AND NOTE IN ('Response dispatched — officer-confirmed quick-win batch','Moved on board (drag)')
  AND CASE_ID IN (
    SELECT CASE_ID FROM FOI.FOI_SENTINEL_V2.FOI_CASE
    WHERE REFERENCE IN ('FOI-2026-0108','FOI-2026-0109','FOI-2026-0126','FOI-2026-0128','FOI-2026-0114','FOI-2026-0102','FOI-2026-0119')
  );

-- Verify
SELECT REFERENCE, CURRENT_STAGE, STATUS, OUTCOME, CLOSED_DATE
FROM FOI.FOI_SENTINEL_V2.FOI_CASE
WHERE REFERENCE IN ('FOI-2026-0108','FOI-2026-0109','FOI-2026-0126','FOI-2026-0128','FOI-2026-0114','FOI-2026-0102','FOI-2026-0119','FOI-2026-0115')
ORDER BY REFERENCE;
